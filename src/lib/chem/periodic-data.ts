/**
 * Full periodic table (Z = 1 to 118) and the long-form layout helpers used by the
 * Class 11 Unit 3 (Classification of Elements and Periodicity in Properties) pages.
 *
 * Data source: PubChem's public-domain periodic table, snapshot committed at
 * `src/lib/chem/data/pubchem-periodic-table.json`, downloaded 2026-11-14 (UTC) from
 * https://pubchem.ncbi.nlm.nih.gov/rest/pug/periodictable/JSON. The PERIODIC_TABLE
 * records below were generated from that snapshot, not typed by hand. Where NCERT
 * prints a different value, NCERT's value is used in `ncert-unit3-tables.ts`, and
 * the disagreements are listed in that file's comments.
 *
 * Conventions (NCERT Class 11 Unit 3, sections 3.5 to 3.7):
 * - Long form, 18 columns. Lanthanoids Ce (Z = 58) to Lu (Z = 71) and actinoids
 *   Th (Z = 90) to Lr (Z = 103) are detached below the main table (rows 9 and 10).
 * - La (Z = 57) and Ac (Z = 89) sit in group 3, row 6 and row 7, as the NCERT text
 *   starts the 4f and 5f series at Ce and Th.
 * - Helium is an s-block element placed in group 18. Hydrogen is in group 1.
 * - Category follows NCERT where the text names an element (Si, Ge, As, Sb, Te are
 *   metalloids). Other elements follow PubChem's classification.
 */

import { electronConfiguration } from './quantum'

/** Orbital block of an element, from the subshell that receives its last electron. */
export type Block = 's' | 'p' | 'd' | 'f'

/** NCERT's three-way classification (section 3.6.5). */
export type Category = 'metal' | 'non-metal' | 'metalloid'

/** Which detached f-block row an element belongs to, or null for the main table. */
export type FBlockRow = 'lanthanoid' | 'actinoid' | null

/** One element of the periodic table. Energies are for isolated gaseous atoms. */
export interface ElementRecord {
  /** Atomic number Z */
  Z: number
  symbol: string
  /** English name from PubChem (US spelling where PubChem uses it, e.g. "Aluminum") */
  name: string
  /** NCERT's spelling, present only where it differs from `name` */
  ncertName?: string
  /** Standard atomic weight in u (g mol⁻¹ numerically) */
  atomicMass: number
  /** Group 1 to 18 in the long form, or null for the detached f-block rows */
  group: number | null
  /** Period 1 to 7 */
  period: number
  block: Block
  fBlockRow: FBlockRow
  category: Category
  /** PubChem's class label, kept so the category decision can be audited */
  pubchemGroupBlock: string
  /** Pauling electronegativity, or null when undefined */
  electronegativity: number | null
  /** PubChem atomic radius in pm (covalent, metallic or empirical as PubChem gives it) */
  atomicRadiusPm: number | null
  /** First ionization energy in eV, as PubChem gives it */
  firstIonizationEnergyEv: number | null
  /** First ionization energy in kJ mol⁻¹ (eV × 96.485, rounded to 0.1) */
  firstIonizationEnergyKjPerMol: number | null
  /**
   * Electron affinity in eV, as PubChem gives it. Positive means energy is released when
   * an electron is added. NCERT's electron gain enthalpy is the negative of this in kJ mol⁻¹.
   */
  electronAffinityEv: number | null
  standardState: string
}

/** A position in the printed long-form grid. Rows 1 to 7 are periods, 9 and 10 the f-block rows. */
export interface TablePosition {
  row: number
  col: number
}

