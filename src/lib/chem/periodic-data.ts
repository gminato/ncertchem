const BY_Z: ReadonlyMap<number, ElementRecord> = new Map(PERIODIC_TABLE.map((e) => [e.Z, e]))

function requireZ(Z: number): void {
  if (!Number.isInteger(Z) || Z < 1 || Z > PERIODIC_TABLE.length) {
    throw new RangeError(`Atomic number Z must be an integer from 1 to 118 (received ${Z})`)
  }
}

/**
 * Returns the record for atomic number Z.
 *
 * @throws {RangeError} If Z is not an integer from 1 to 118
 */
export function elementByZ(Z: number): ElementRecord {
  requireZ(Z)
  return BY_Z.get(Z) as ElementRecord
}

/** Returns the record with the given chemical symbol, or undefined if there is none. */
export function elementBySymbol(symbol: string): ElementRecord | undefined {
  return PERIODIC_TABLE.find((e) => e.symbol === symbol)
}

/**
 * Position of element Z in the printed long form. Main-table elements use row = period and
 * col = group. Lanthanoids (Ce to Lu) use row 9 and col = Z − 55 (Ce at col 3). Actinoids
 * (Th to Lr) use row 10 and col = Z − 87.
 *
 * @throws {RangeError} If Z is not an integer from 1 to 118
 */
export function tablePosition(Z: number): TablePosition {
  const e = elementByZ(Z)
  if (e.fBlockRow === 'lanthanoid') return { row: 9, col: Z - 55 }
  if (e.fBlockRow === 'actinoid') return { row: 10, col: Z - 87 }
  return { row: e.period, col: e.group as number }
}

/**
 * Group (1 to 18) of element Z in the long form, or null for the detached f-block rows.
 *
 * @throws {RangeError} If Z is not an integer from 1 to 118
 */
export function groupOf(Z: number): number | null {
  return elementByZ(Z).group
}

/**
 * Period (1 to 7) of element Z.
 *
 * @throws {RangeError} If Z is not an integer from 1 to 118
 */
export function periodOf(Z: number): number {
  return elementByZ(Z).period
}

/**
 * Block of element Z: s, p, d or f.
 *
 * @throws {RangeError} If Z is not an integer from 1 to 118
 */
export function blockOf(Z: number): Block {
  return elementByZ(Z).block
}

/**
 * Number of valence electrons of a representative (s- and p-block) element: the group
 * number for groups 1 and 2, and group − 10 for groups 13 to 18. Helium has 2.
 * Returns null for d- and f-block elements.
 *
 * @throws {RangeError} If Z is not an integer from 1 to 118
 */
export function valenceElectrons(Z: number): number | null {
  const e = elementByZ(Z)
  if (Z === 2) return 2
  if (e.block === 'd' || e.block === 'f' || e.group === null) return null
  if (e.group <= 2) return e.group
  return e.group - 10
}

/**
 * Valence values of a representative element, as in NCERT section 3.7.2(a). The valence is
 * the number of valence electrons, or eight minus that number. Table 3.9 shows both values
 * for groups 15 to 17 and group 18, and one value for groups 1, 2, 13 and 14.
 * Returns an empty array for d- and f-block elements.
 *
 * @throws {RangeError} If Z is not an integer from 1 to 118
 */
export function typicalValence(Z: number): number[] {
  const v = valenceElectrons(Z)
  if (v === null) return []
  if (Z === 2) return [0]
  const group = elementByZ(Z).group as number
  if (group >= 15 && group <= 17) return [8 - v, v].sort((a, b) => a - b)
  if (group === 18) return [0, 8]
  return [v]
}

const SUPERSCRIPT_DIGITS = ['⁰', '¹', '²', '³', '⁴', '⁵', '⁶', '⁷', '⁸', '⁹']

function superscript(n: number): string {
  return String(n)
    .split('')
    .map((d) => SUPERSCRIPT_DIGITS[Number(d)])
    .join('')
}

/**
 * Outer electronic configuration of a representative element, written with its period as
 * the principal quantum number, e.g. "3s¹" for Na, "3s²3p⁵" for Cl and "1s²" for He. For
 * predicted elements (Z = 113 onward) this follows the group, not measured spectra.
 * Returns null for d- and f-block elements.
 *
 * @throws {RangeError} If Z is not an integer from 1 to 118
 */
export function outerConfiguration(Z: number): string | null {
  const e = elementByZ(Z)
  if (Z === 1) return '1s¹'
  if (Z === 2) return '1s²'
  if (e.block === 'd' || e.block === 'f' || e.group === null) return null
  const n = e.period
  if (e.group <= 2) return `${n}s${superscript(e.group)}`
  return `${n}s²${n}p${superscript(e.group - 12)}`
}

/** Subshell l value: s = 0, p = 1, d = 2, f = 3. */
const L_OF_LETTER: Readonly<Record<string, number>> = { s: 0, p: 1, d: 2, f: 3 }

/** Slater group rank within a principal shell: s/p = 0, d = 1, f = 2. */
function slaterKey(n: number, l: number): number {
  const rank = l <= 1 ? 0 : l === 2 ? 1 : 2
  return n * 10 + rank
}

/**
 * Slater's-rules effective nuclear charge felt by the outermost electron of element Z
 * (Z = 1 to 36). The outermost electron is taken as the highest-l s or p electron of the
 * highest occupied shell, or a d electron if that shell has no s or p electrons. Ground
 * states come from {@link electronConfiguration}, so the Cr and Cu exceptions apply.
 *
 * Shielding constants follow Slater (1930). For an s or p target: 0.35 per other electron
 * in the same group (0.30 for 1s), 0.85 per electron in shell n − 1, 1.00 per electron in
 * shell n − 2 or lower. For a d target: 0.35 per other electron in the same group, 1.00 per
 * electron in any group to its left, 0 for groups to its right.
 *
 * NCERT discusses effective nuclear charge only qualitatively (section 3.7.1(c)). This is a
 * textbook estimate used to explain trends. Values: Na 2.20, Mg 2.85, Cl 6.10, K 2.20.
 *
 * @throws {RangeError} If Z is not an integer from 1 to 36
 */
export function slaterZeff(Z: number): number {
  if (!Number.isInteger(Z) || Z < 1 || Z > 36) {
    throw new RangeError(`slaterZeff is defined for Z from 1 to 36 (received ${Z})`)
  }
  const occupied = electronConfiguration(Z).subshells.map(({ label, electrons }) => ({
    n: Number(label[0]),
    l: L_OF_LETTER[label[1]],
    electrons,
  }))
  const nMax = Math.max(...occupied.map((s) => s.n))
  const valenceShell = occupied.filter((s) => s.n === nMax)
  const spCandidates = valenceShell.filter((s) => s.l <= 1)
  const target = spCandidates.length > 0
    ? spCandidates.reduce((a, b) => (b.l > a.l ? b : a))
    : valenceShell[0]

  const targetKey = slaterKey(target.n, target.l)
  let shielding = 0
  for (const s of occupied) {
    const count = s === target ? s.electrons - 1 : s.electrons
    if (count <= 0) continue
    const key = slaterKey(s.n, s.l)
    if (target.l <= 1) {
      if (key === targetKey) {
        shielding += count * (Z === 1 || Z === 2 ? 0.3 : 0.35)
      } else if (s.n === target.n - 1) {
        shielding += count * 0.85
      } else if (s.n <= target.n - 2) {
        shielding += count
      }
    } else {
      if (key === targetKey) {
        shielding += count * 0.35
      } else if (key < targetKey) {
        shielding += count
      }
    }
  }
  return Z - shielding
}

/**
 * Returns the indices of the first ionization energies that fall from one main-group element
 * to the next within a period, with the reason NCERT gives (section 3.7.1(c)).
 *
 * @throws {RangeError} If period is not an integer from 1 to 7
 */
export function ionizationAnomalies(period: number): IonizationAnomaly[] {
  if (!Number.isInteger(period) || period < 1 || period > 7) {
    throw new RangeError(`Period must be an integer from 1 to 7 (received ${period})`)
  }
  const inPeriod = PERIODIC_TABLE.filter(
    (e) => e.period === period && (e.block === 's' || e.block === 'p'),
  )
  const result: IonizationAnomaly[] = []
  for (let i = 0; i + 1 < inPeriod.length; i++) {
    const a = inPeriod[i]
    const b = inPeriod[i + 1]
    if (b.Z !== a.Z + 1 || a.firstIonizationEnergyKjPerMol === null || b.firstIonizationEnergyKjPerMol === null) continue
    if (b.firstIonizationEnergyKjPerMol < a.firstIonizationEnergyKjPerMol) {
      const reason: IonizationAnomalyReason | null = b.group === 13
        ? 'p-electron-shielded'
        : b.group === 16
          ? 'paired-electron-repulsion'
          : null
      if (reason) result.push({ from: a.Z, to: b.Z, reason })
    }
  }
  return result
}

/** Reason a first ionization energy dips, as in NCERT section 3.7.1(c). */
export type IonizationAnomalyReason = 'p-electron-shielded' | 'paired-electron-repulsion'

/** One dip in first ionization energy between consecutive elements Z = from and Z = to. */
export interface IonizationAnomaly {
  from: number
  to: number
  reason: IonizationAnomalyReason
}
